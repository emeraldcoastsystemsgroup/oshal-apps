import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const framework = process.env.OSHAL_FRAMEWORK;
if (!framework) throw new Error('set OSHAL_FRAMEWORK to the oshal/src checkout');
const here = dirname(fileURLToPath(import.meta.url));
const services = join(framework, 'src/features/trading/services');
const entry = join(mkdtempSync(join(tmpdir(), 'futures-engine-')), 'entry.ts');
writeFileSync(entry, [
  `export { DEFAULT_OPTIMIZER_STAGES, runStagedOptimizer } from '${services}/futures-optimizer';`,
  `export { walkForwardWindows } from '${services}/futures-walk-forward';`,
  `export { runFuturesBacktest } from '${services}/futures-backtester';`,
  `export { buildContinuousSeries } from '${services}/futures-continuous';`,
  `export { getFuturesRoot, contractsForRange } from '${services}/futures-contract';`,
].join('\n') + '\n');
const out = join(here, '..', 'routes', 'futures', 'engine.js');
execFileSync(join(framework, 'node_modules/.bin/esbuild'), [entry, '--bundle', '--platform=node', '--format=cjs', '--target=node20',
  '--external:@/shared/logger', `--tsconfig=${join(framework, 'tsconfig.json')}`, `--outfile=${out}`], { stdio: 'inherit' });
const commit = execFileSync('git', ['-C', framework, 'rev-parse', 'HEAD']).toString().trim();
// The host supplies @/shared/logger (the native bridge, the platform); a plain Node or vitest require has no such
// module, so the bundle falls back to a quiet logger there instead of failing to load.
const QUIET = '(() => { try { return require("@/shared/logger"); } catch { const l = { info() {}, warn() {}, error() {}, debug() {}, child() { return l; } }; return { createChildLogger: () => l }; } })()';
const body = readFileSync(out, 'utf8').split('require("@/shared/logger")').join(QUIET);
writeFileSync(out, `/* GENERATED by tools/build-futures-engine.mjs from oshal platform ${commit} (src/features/trading/services/futures-*.ts). Do not edit; regenerate. */\n${body}`);
console.log('wrote', out, 'from', commit);
