'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const { createHash } = require('node:crypto');
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const net = require('node:net');
const os = require('node:os');
const path = require('node:path');

const PKG = path.resolve(__dirname, '..');
const ENGINE = path.join(PKG, 'engine');
const slicer = require(path.join(PKG, 'routes/engine/print/slicer.js'));
const client = require(path.join(PKG, 'routes/printing/slicer-engine.js'));

const SAMPLE_GCODE = '; generated by OrcaSlicer 2.4.2\n; total layer number: 25\n; filament used [g] = 1.45\n; estimated printing time (normal mode) = 3m 12s\nG90\nG28\nG1 X10 Y10 Z0.2 F1200\nM84\n';

function gcodeResult(text = SAMPLE_GCODE, overrides = {}) {
  const buf = Buffer.from(text, 'utf8');
  return {
    ok: true,
    fileName: 'part.gcode',
    gcodeBase64: buf.toString('base64'),
    bytes: buf.length,
    sha256: createHash('sha256').update(buf).digest('hex'),
    slicer: 'orca-slicer',
    estimate: { printSeconds: 192, filamentGrams: 1.45, filamentMm: 480.2, layers: 25 },
    profile: { name: 'marlin', gcodeFlavor: 'marlin' },
    ...overrides,
  };
}

test('resolveSlicerBackend prioritizes explicit command, falls back to engine, else none', () => {
  assert.deepEqual(slicer.resolveSlicerBackend({}, false), { configured: false, backend: 'none', command: null });
  assert.deepEqual(slicer.resolveSlicerBackend({}, true), { configured: true, backend: 'engine', command: null });
  const withCmd = slicer.resolveSlicerBackend({ SCAN_TO_PRINT_SLICER_CMD: 'orca {input} {output}' }, true);
  assert.equal(withCmd.configured, true);
  assert.equal(withCmd.backend, 'command');
  assert.equal(withCmd.command.command, 'orca {input} {output}');
  // Malformed SCAN_TO_PRINT_SLICER_CMD does not crash; engine fallback remains available when configured.
  const badCmd = slicer.resolveSlicerBackend({ SCAN_TO_PRINT_SLICER_CMD: 'missing-placeholders' }, true);
  assert.equal(badCmd.backend, 'engine');
});

test('parseGcodeSliceSettings validates bounds, profiles, and rejects out-of-range inputs', () => {
  assert.deepEqual(slicer.parseGcodeSliceSettings(undefined), {});
  assert.deepEqual(slicer.parseGcodeSliceSettings({
    layerHeightMm: 0.16, infillPct: 25, wallLoops: 3, nozzleTempC: 215, bedTempC: 65, profile: 'Moonraker',
  }), { layerHeightMm: 0.16, infillPct: 25, wallLoops: 3, nozzleTempC: 215, bedTempC: 65, profile: 'klipper' });
  assert.equal(slicer.defaultGcodeProfileForKind('moonraker'), 'klipper');
  assert.equal(slicer.defaultGcodeProfileForKind('octoprint'), 'marlin');
  assert.equal(slicer.defaultGcodeProfileForKind('prusalink'), 'marlin');
  for (const bad of [
    { layerHeightMm: 0.01 }, { layerHeightMm: 0.9 }, { infillPct: 105 }, { infillPct: 12.5 },
    { wallLoops: 0 }, { nozzleTempC: 400 }, { bedTempC: -1 }, { profile: 'unknown-printer' },
  ]) {
    assert.throws(() => slicer.parseGcodeSliceSettings(bad), RangeError, JSON.stringify(bad));
  }
});

test('isEngineGcodeConfigured detects native exchange, socket seam, and valid SCAN_TO_PRINT_ENGINE_ADDR', () => {
  const base = { host: 'scan-to-print-engine', port: 7414, expectedBuildHash: 'a'.repeat(64), installHint: 'sh install-engine.sh' };
  assert.equal(client.isEngineGcodeConfigured(base, {}), false);
  assert.equal(client.isEngineGcodeConfigured({ ...base, exchange: async () => ({}) }, {}), true);
  assert.equal(client.isEngineGcodeConfigured({ ...base, connect: () => null }, {}), true);
  assert.equal(client.isEngineGcodeConfigured(base, { SCAN_TO_PRINT_ENGINE_ADDR: '10.254.233.8:7414' }), true);
  assert.equal(client.isEngineGcodeConfigured({ ...base, addrError: 'bad' }, { SCAN_TO_PRINT_ENGINE_ADDR: 'bad' }), false);
});

test('sliceToGcode over engine.exchange verifies SHA-256, rejects tampering, and flags older engines', async () => {
  const hello = { bridge: { protocol: client.SLICER_BRIDGE_PROTOCOL, buildHash: 'a'.repeat(64), capabilities: ['hello', 'slice', 'slice_gcode'] } };
  const seen = [];
  const opts = {
    host: '', port: 0, expectedBuildHash: 'a'.repeat(64), installHint: 'sh scan-to-print/engine/install-engine.sh',
    exchange: async (request, timeoutMs) => { seen.push({ request, timeoutMs }); return { hello, reply: { ok: true, result: gcodeResult() } }; },
  };
  const out = await client.sliceToGcode(opts, Buffer.from('solid cube\nendsolid cube\n'), 'cube', { layerHeightMm: 0.2, infillPct: 20, profile: 'marlin' });
  assert.equal(seen[0].request.cmd, 'slice_gcode');
  assert.equal(seen[0].request.args.infillPct, 20);
  assert.equal(out.slicer, 'orca-slicer');
  assert.equal(Buffer.from(out.bytes).toString('utf8'), SAMPLE_GCODE);
  assert.equal(out.estimate.printSeconds, 192);
  assert.equal(out.estimate.layers, 25);

  await assert.rejects(
    client.sliceToGcode({ ...opts, exchange: async () => ({ hello, reply: { ok: true, result: gcodeResult(SAMPLE_GCODE, { sha256: '0'.repeat(64) }) } }) }, Buffer.from('x'), 'cube'),
    (error) => error.code === 'engine_error' && /integrity verification/.test(error.message),
  );
  await assert.rejects(
    client.sliceToGcode({ ...opts, exchange: async () => ({ hello, reply: { ok: false, error: { code: 'refused', message: "unknown command 'slice_gcode'" } } }) }, Buffer.from('x'), 'cube'),
    (error) => error.code === 'unavailable' && /install-engine\.sh/.test(error.reason),
  );
});

test('sliceToGcode over loopback TCP bridge enforces build hash and returns validated G-code', async () => {
  const hash = client.slicerEngineBuildHash(ENGINE);
  const server = net.createServer((socket) => {
    socket.on('error', () => {});
    socket.write(JSON.stringify({ bridge: { protocol: 1, buildHash: hash, capabilities: ['hello', 'profiles', 'slice', 'slice_gcode', 'upload_bambu'] } }) + '\n');
    let buf = '';
    socket.on('data', (chunk) => {
      buf += chunk.toString('utf8');
      let i;
      while ((i = buf.indexOf('\n')) >= 0) {
        const req = JSON.parse(buf.slice(0, i)); buf = buf.slice(i + 1);
        socket.write(JSON.stringify({ id: req.id, ok: true, result: gcodeResult() }) + '\n');
      }
    });
  });
  await new Promise((r) => server.listen(0, '127.0.0.1', r));
  try {
    const out = await client.sliceToGcode(
      { host: '127.0.0.1', port: server.address().port, expectedBuildHash: hash, installHint: 'sh install-engine.sh', timeoutMs: 5000 },
      Buffer.from('solid part\nendsolid part\n'), 'part', { profile: 'klipper' },
    );
    assert.equal(out.bytes.byteLength, Buffer.byteLength(SAMPLE_GCODE));
    assert.equal(out.slicer, 'orca-slicer');
  } finally { await new Promise((r) => server.close(r)); }
});

test('real engine/slicer_worker.py serves hello and slice_gcode cleanly over stdio JSON-lines', () => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'scan-worker-gcode-'));
  try {
    const mk = (rel, obj) => {
      const full = path.join(tmp, rel);
      fs.mkdirSync(path.dirname(full), { recursive: true });
      fs.writeFileSync(full, JSON.stringify(obj));
    };
    mk('resources/profiles/Custom/machine/MyMarlin 0.4 nozzle.json', { name: 'MyMarlin 0.4 nozzle', gcode_flavor: 'marlin', nozzle_diameter: ['0.4'] });
    mk('resources/profiles/Custom/process/0.20mm Standard @MyMarlin.json', { name: '0.20mm Standard @MyMarlin', layer_height: '0.2' });
    mk('resources/profiles/OrcaFilamentLibrary/filament/Generic PLA @System.json', { name: 'Generic PLA @System', filament_type: ['PLA'] });
    const binDir = path.join(tmp, 'bin');
    fs.mkdirSync(binDir, { recursive: true });
    const fakeOrca = path.join(binDir, 'orca-slicer');
    fs.writeFileSync(fakeOrca, `#!/usr/bin/env python3\nimport json, os, sys\nd = sys.argv[sys.argv.index('--outputdir') + 1]\nopen(os.path.join(d, 'result.json'), 'w').write(json.dumps({'return_code': 0}))\nopen(os.path.join(d, 'plate_1.gcode'), 'w').write(${JSON.stringify(SAMPLE_GCODE)})\n`, { mode: 0o755 });
    const input = [
      JSON.stringify({ id: 1, cmd: 'hello' }),
      JSON.stringify({ id: 2, cmd: 'slice_gcode', args: { stl: Buffer.from('solid box\nendsolid box\n').toString('base64'), name: 'box', profile: 'marlin', layerHeightMm: 0.2, infillPct: 20 } }),
    ].join('\n') + '\n';
    const stdout = execFileSync('python3', [path.join(ENGINE, 'slicer_worker.py')], {
      input, encoding: 'utf8', env: { ...process.env, ORCA_SLICER_DIR: tmp },
    });
    const lines = stdout.trim().split('\n').map((l) => JSON.parse(l));
    assert.equal(lines.length, 2);
    assert.equal(lines[0].ok, true);
    assert.ok(lines[0].result.capabilities.includes('slice_gcode'));
    assert.equal(lines[1].ok, true);
    assert.equal(lines[1].result.slicer, 'orca-slicer');
    assert.equal(Buffer.from(lines[1].result.gcodeBase64, 'base64').toString('utf8'), SAMPLE_GCODE);
  } finally { fs.rmSync(tmp, { recursive: true, force: true }); }
});
